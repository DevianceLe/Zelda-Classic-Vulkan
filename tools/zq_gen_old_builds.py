"""Writes src/port/zqeditor/zq_builds_old_table.h: the section versions each ZC build from 1.90 to
2.53.1 writes, from that build's own zdefs.h in the zc-history repository (git show only).

    python tools/zq_gen_old_builds.py [H:\\zc-history]

Each row: the build's name, the header it writes (zelda_version, build) and the version and
cversion of every section it writes (0: the build writes no such section). 1.90 and 1.92 quests
have no sections (one body after the header), so their rows hold only the header.

Header builds where zc-history and the files the releases wrote disagree (see NOTE below) are set
from upstream's own table of builds (zquestheader::getVerStr in upstream 3.0's zdefs.cpp) and the
templates the releases shipped.
"""
import os
import re
import subprocess
import sys

HIST = sys.argv[1] if len(sys.argv) > 1 else r'H:\zc-history'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'port', 'zqeditor', 'zq_builds_old_table.h')

# (name, git ref, zdefs.h path, header build override or None, note)
BUILDS = [
    ('2.10.0', 'origin/2.10', 'zdefs.h', None, ''),
    ('2.10.1', 'origin/2.10.1', 'zdefs.h', None, ''),
    ('2.10.2', 'origin/2.10.2', 'zdefs.h', None, ''),
    ('2.10.3', 'origin/2.10.3', 'zdefs.h', None, ''),
    ('2.11 Beta 11', '4260875a', 'zdefs.h', None, ''),
    ('2.11 Beta 12', 'a1fc3392', 'zdefs.h', None, ''),
    ('2.11 Beta 13', '50b1bc04', 'zdefs.h', None, ''),
    ('2.11 Beta 14', '77172d36', 'zdefs.h', None, ''),
    ('2.11 Beta 15', '5eee8fc8', 'zdefs.h', None, ''),
    ('2.11 Beta 18', 'origin/2.11-Betas', 'zdefs.h', None, ''),
    ('2.50.0', 'origin/2.50.0', 'zdefs.h', None, ''),
    ('2.50.1', 'origin/2.50.1', 'zdefs.h', None, ''),
    # NOTE: zc-history's 2.50.2 branch says build 28 (2.50.1's number, with 2.50.1's qst.dat) and its
    # 2.50.3-RC1 tag says 29. The releases' files say otherwise: 2.50.2 wrote build 29 (upstream's
    # table, its loader's "build == 29 //2.50.2", and the 2.50.3-RC1 tree's qst.dat, which 2.50.2's
    # ZQuest saved, is build 29); 2.50.3 is build 30 ("2.50.3, Gamma 1").
    ('2.50.2', 'origin/2.50.2', 'zdefs.h', 29, 'header build 29 (zc-history: 28)'),
    ('2.50.3', '2.50.3-RC1', 'zdefs.h', 30, 'header build 30 (zc-history: 29)'),
    ('2.53.0', '6c255b4d', 'src/zdefs.h', None, ''),
    ('2.53.1', 'origin/2.53.0', 'src/zdefs.h', None, ''),
]

SECTIONS = ['HEADER', 'RULES', 'STRINGS', 'MISC', 'TILES', 'COMBOS', 'CSETS', 'MAPS', 'DMAPS', 'DOORS', 'ITEMS',
            'WEAPONS', 'COLORS', 'ICONS', 'INITDATA', 'GUYS', 'MIDIS', 'CHEATS', 'COMBOALIASES', 'LINKSPRITES',
            'SUBSCREEN', 'ITEMDROPSETS', 'FFSCRIPT', 'SFX', 'FAVORITES']
ALIASES = {'ITEMDROPSETS': ['ITEMDROPSETS', 'ITEMDROPSET']}


def defines(ref, path):
    text = subprocess.run(['git', '-C', HIST, 'show', '%s:%s' % (ref, path)], capture_output=True, check=True).stdout
    text = text.decode('latin-1')
    d = {}
    for m in re.finditer(r'^\s*#define\s+(\w+)\s+([^\s/]+)', text, re.M):
        d.setdefault(m.group(1), m.group(2))   # the first one: 1.92's file keeps older ones under #if 0
    return d


def num(s):
    return int(s, 0)


def main():
    rows = []
    for name, ref, path, override, note in BUILDS:
        d = defines(ref, path)
        zv = num(d['ZELDA_VERSION'])
        build = override if override is not None else num(d['VERSION_BUILD'])
        secs = []
        for s in SECTIONS:
            v = cv = 0
            for a in ALIASES.get(s, [s]):
                if 'V_' + a in d:
                    v = num(d['V_' + a])
                    cvs = [d['CV_' + b] for b in ALIASES.get(s, [s]) if 'CV_' + b in d]
                    cv = num(cvs[0]) if cvs else 1
                    break
            secs.append((v, cv))
        rows.append((name, ref, zv, build, secs, note))

    with open(OUT, 'w', newline='\n') as f:
        f.write('// zq_builds_old_table.h: generated by tools/zq_gen_old_builds.py from each build\'s zdefs.h in\n')
        f.write('// zc-history. Do not edit; run the script again.\n//\n')
        f.write('// Each build: its name, the header it writes, and the version and cversion of each section it\n')
        f.write('// writes, in ZqOldSection order (0: no such section).\n\n')
        f.write('#pragma once\n\n')
        f.write('enum ZqOldSection\n{\n')
        for i, s in enumerate(SECTIONS):
            f.write('    ZQOS_%s,\n' % s)
        f.write('    ZQOS_COUNT\n};\n\n')
        f.write('struct ZqOldBuildTable\n{\n    const char *name;\n    word zelda_version;\n    byte build;\n')
        f.write('    word version[ZQOS_COUNT], cversion[ZQOS_COUNT];\n};\n\n')
        f.write('static const ZqOldBuildTable zq_old_build_table[] =\n{\n')
        for name, ref, zv, build, secs, note in rows:
            f.write('    // %s: %s%s\n' % (name, ref, ('; ' + note) if note else ''))
            f.write('    { "%s", 0x%X, %d,\n      { %s },\n      { %s } },\n' % (
                name, zv, build, ', '.join(str(v) for v, cv in secs), ', '.join(str(cv) for v, cv in secs)))
        f.write('};\n\nstatic const int zq_old_build_table_count = (int)(sizeof(zq_old_build_table) / sizeof(zq_old_build_table[0]));\n')
    print('wrote', os.path.normpath(OUT), len(rows), 'builds')


if __name__ == '__main__':
    main()
