# Generates src/port/zqeditor/zq_engravings.cpp from upstream's editor asset
# resources/assets/editor/engravings.bmp (GPL, ZQuest Classic): the 16x16 pictures beside each
# autocombo slot in its editor. 512 slots of 16x16 in a grid of 17-pixel cells (16 a row), 8-bit,
# drawn with ZQuest's editor palette (resources/assets/editor/pal.bmp); index 0 is transparent.
# Each slot becomes 256 hex digits (one colour code per pixel), and the colours an RGBA table.
#   python -I tools/zq_gen_engravings.py <engravings.bmp> <pal.bmp> <out.cpp>
import struct, sys

bmp_path, pal_path, out = sys.argv[1], sys.argv[2], sys.argv[3]

def read_bmp(path):
    d = open(path, 'rb').read()
    off = struct.unpack('<I', d[10:14])[0]
    w, h = struct.unpack('<ii', d[18:26])
    bpp = struct.unpack('<H', d[28:30])[0]
    assert bpp == 8
    pal = d[54:54 + 1024]
    stride = (w + 3) & ~3
    rows = [d[off + (h - 1 - y) * stride: off + (h - 1 - y) * stride + w] for y in range(h)]
    return w, h, rows, pal

w, h, rows, _ = read_bmp(bmp_path)
_, _, _, pal = read_bmp(pal_path)
slots = []
used = set()

for s in range(512):
    bx = 1 + (s % 16) * 17
    by = 1 + (s // 16) * 17
    cell = []
    for y in range(16):
        cell += list(rows[by + y][bx:bx + 16])
    slots.append(cell)
    used |= set(cell)

colours = sorted(used)
assert colours[0] == 0 and len(colours) <= 16
code = dict((c, i) for i, c in enumerate(colours))

with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/zq_gen_engravings.py from upstream ZQuest Classic\'s editor assets\n')
    f.write('// (resources/assets/editor/engravings.bmp and pal.bmp, GPL). Do not edit.\n')
    f.write('//\n// The pictures beside each autocombo slot in the autocombo editor: 512 slots of 16x16, one\n')
    f.write('// hex digit per pixel naming a colour of zq_engraving_rgba (0: transparent).\n\n')
    f.write('#include "zq_engravings.h"\n\n')
    f.write('const unsigned int zq_engraving_rgba[16] =\n{\n')
    for i in range(16):
        if i < len(colours) and colours[i] != 0:
            c = colours[i]
            b, g, r = pal[c * 4], pal[c * 4 + 1], pal[c * 4 + 2]
            f.write('    0xFF%02X%02X%02Xu,   // editor palette %d\n' % (b, g, r, c))
        else:
            f.write('    0x00000000u,\n')
    f.write('};\n\n')
    f.write('const char *const zq_engravings[512] =\n{\n')
    for s in range(512):
        cell = slots[s]
        if not any(cell):
            f.write('    0,\n')
            continue
        digits = ''.join('%x' % code[p] for p in cell)
        f.write('    "%s"\n    "%s",\n' % (digits[:128], digits[128:]))
    f.write('};\n')
