# Writes src/port/zqeditor/zq_new_rulesets.h: upstream ZQuest's rulesets and rule templates (File > New's
# tileset wizard, Quest > Rulesets) as the rule numbers each generation's quests store, from upstream's own
# source: 2.55 = 2.55.18's, 3.0 Nightly = 3.0's (zq/zq_files.cpp applyRuleset and alwaysOnRules,
# dialog/quest_rules.cpp applyRuleTemplate and compatRulesList, the generation's qrs.h).
#   python -I tools/zq_gen_new_rulesets.py <upstream 2.55.18 tree> <upstream 3.0 tree> <out .h>
import re, sys


def strip(t):
    t = re.sub(r'/\*.*?\*/', ' ', t, flags=re.S)
    return re.sub(r'//[^\n]*', ' ', t)


def qr_numbers(path):
    t = strip(open(path, encoding='utf-8', errors='replace').read())
    a = t.index('qr_SOLIDBLK')
    t = t[a:t.index('qr_MAX', a) + 6]
    nums, n = {}, 0
    for tok in t.split(','):
        tok = tok.strip()
        if not tok:
            continue
        if '=' in tok:
            name, expr = [x.strip() for x in tok.split('=', 1)]
            n = eval(expr, {}, {})
        else:
            name = tok
        nums[name] = n
        n += 1
    return nums


def block(t, start):
    a = t.index(start)
    a = t.index('{', a)
    depth, i = 0, a
    while True:
        if t[i] == '{':
            depth += 1
        elif t[i] == '}':
            depth -= 1
            if not depth:
                return t[a + 1:i]
        i += 1


def arr(t, name):
    m = re.search(r'\b' + name + r'\s*\[\s*\]\s*=\s*\{(.*?)\};', t, re.S)
    return re.findall(r'qr_\w+', m.group(1)) if m else None


def gen(tree, qrs):
    nums = qr_numbers(tree + qrs)
    zf = strip(open(tree + '/src/zq/zq_files.cpp', encoding='utf-8', errors='replace').read())
    qd = strip(open(tree + '/src/dialog/quest_rules.cpp', encoding='utf-8', errors='replace').read())
    ar = zf[zf.index('void applyRuleset'):]
    L = {}
    for n in ('rALWAYS_ON', 'r_FIXES', 'rNES', 'rBSZ', 'rZ3', 'rMODERN', 'r_NON_MODERN', 'rMODERN_O'):
        L[n] = arr(ar, n) or []
    if not L['rALWAYS_ON']:      # 2.55: alwaysOnRules() sets them one by one
        L['rALWAYS_ON'] = re.findall(r'set_qr\(\s*(qr_\w+)\s*,\s*1\s*\)', block(zf, 'void alwaysOnRules()'))
    L['KEEP'] = re.findall(r'case\s+(qr_\w+)\s*:', ar[:ar.index('default:')])
    for n in ('zsOnRules', 'zsOffRules', 'subscr_rules_off', 'subscr_rules_on'):
        L[n] = arr(qd, n)
    L['COMPAT'] = re.findall(r'qr_\w+', block(qd, 'GUI::ListData compatRulesList'))
    # the rulesets' steps in upstream's order: (value, lists)
    sw = block(ar, 'switch(ruleset)')
    rs = {}
    for name, label in (('NES', 'rulesetNES'), ('FIXEDNES', 'rulesetFixedNES'), ('BSZ', 'rulesetBSZ'), ('Z3', 'rulesetZ3'),
                        ('MODERN', 'rulesetModern')):
        body = block(sw, 'case ' + label + ':')
        rs[name] = re.findall(r'for\s*\(\s*auto\s+qr\s*:\s*(\w+)\s*\)\s*set_qr\(\s*qr\s*,\s*([01])', body)
        rs[name + '_TMPL'] = 'applyRuleTemplate' in body
    return nums, L, rs


if __name__ == '__main__':
    T = (('255', sys.argv[1], '/src/base/qrs.h'), ('30', sys.argv[2], '/src/core/qrs.h'))
    out = ['// Generated by tools/zq_gen_new_rulesets.py from upstream ZQuest\'s source (2.55 = 2.55.18, 3.0 Nightly =',
           '// 3.0): its rulesets (zq_files.cpp applyRuleset), rule templates and compat rule list (dialog/quest_rules.cpp),',
           '// as the rule numbers each generation\'s quests store; -1 ends a list. Do not edit.', '',
           '#ifndef ZQ_NEW_RULESETS_H', '#define ZQ_NEW_RULESETS_H', '']
    for g, tree, qrs in T:
        nums, L, rs = gen(tree, qrs)

        def num(x):
            if x not in nums:
                sys.exit('%s: unknown rule %s' % (g, x))
            return str(nums[x])
        for n, names in L.items():
            if names:
                out.append('static const short zqr%s_%s[] = { %s, -1 };' % (g, n.strip('_').upper(), ', '.join(num(x) for x in names)))
        for name in ('NES', 'FIXEDNES', 'BSZ', 'Z3', 'MODERN'):
            pairs = []
            for lst, val in rs[name]:
                pairs += ['%s,%s' % (num(x), val) for x in L[lst]]
            out.append('static const short zqr%s_RS_%s[] = { %s, -1 };   // rule, value' % (g, name, ', '.join(pairs)))
            out.append('static const bool zqr%s_RS_%s_TEMPLATES = %s;' % (g, name, 'true' if rs[name + '_TMPL'] else 'false'))
        for single in ('qr_OLD_STRING_EDITOR_MARGINS', 'qr_STRING_FRAME_OLD_WIDTH_HEIGHT', 'qr_CORRECTED_EW_BRANG_ANIM'):
            out.append('static const short zqr%s_%s = %s;' % (g, single[3:], num(single)))
        out.append('static const short zqr%s_MAX = %d;' % (g, nums['qr_MAX']))
        out.append('')
    out.append('#endif')
    open(sys.argv[3], 'w', newline='\n').write('\n'.join(out) + '\n')
    print('wrote', sys.argv[3])
