"""zq_ui_dialogs_gen.py: the table of every build's ZQuest dialogs the interface profiles lay our editors
out by (src/port/zqeditor/zq_ui_dialogs_table.h), from zquiinv's zq_ui_dialogs.json (each catalog
build's dialogs read out of its own source).

    python tools/zq_ui_dialogs_gen.py <zq_ui_dialogs.json> [<out.h>]

Kept: the DIALOG-array definitions (1.90 to 2.53.x, and 2.55/3.0's older dialogs) of every build's main
editors (zquiinv's "main" categories), and every 2.53.1 one (the reference our editors are told
apart by). A widget: its procedure's name, x, y, w, h, and its text (dp, when a string).
"""
import json
import sys


def c_str(s):
    if s is None:
        return "NULL"
    out = '"'
    for ch in s:
        o = ord(ch)
        if ch == '\\':
            out += '\\\\'
        elif ch == '"':
            out += '\\"'
        elif ch == '\n':
            out += '\\n'
        elif ch == '\t':
            out += '\\t'
        elif o < 32 or o > 126:
            out += '\\%03o' % (o & 0xFF) if o < 256 else '?'
        else:
            out += ch
    return out + '"'


def num(v):
    return v if isinstance(v, int) and -32767 <= v <= 32767 else -32768


def main():
    src = sys.argv[1]
    dst = sys.argv[2] if len(sys.argv) > 2 else "src/port/zqeditor/zq_ui_dialogs_table.h"
    d = json.load(open(src, encoding="utf-8"))
    defs = d["dialogs"]
    uses = []          # (build, name, hash)
    for build, names in d["builds"].items():
        main_names = set()
        for cat, lst in d.get("main", {}).get(build, {}).items():
            main_names.update(lst)
        for name, h in names.items():
            if h not in defs or defs[h].get("kind") != "DIALOG":
                continue
            if build == "2.53.1" or name in main_names:
                uses.append((build, name, h))
    order = []
    index = {}
    for _, _, h in uses:
        if h not in index:
            index[h] = len(order)
            order.append(h)
    lines = []
    lines.append("// zq_ui_dialogs_table.h: generated by tools/zq_ui_dialogs_gen.py from zquiinv's zq_ui_dialogs.json (each")
    lines.append("// catalog build's ZQuest dialogs, read out of its own source). Do not edit; run the script again.")
    lines.append("// Included once, by zq_ui_dialogs.cpp.")
    lines.append("#pragma once")
    lines.append("")
    lines.append("struct ZqUiDlgWidget { const char *type; short x, y, w, h; const char *text; };")
    lines.append("struct ZqUiDlgDef { int first; int count; };")
    lines.append("struct ZqUiDlgUse { const char *build; const char *name; int def; };")
    lines.append("")
    lines.append("static const ZqUiDlgWidget zq_ui_dlg_widgets[] =")
    lines.append("{")
    firsts = []
    total = 0
    for h in order:
        ws = defs[h]["widgets"]
        firsts.append((total, len(ws)))
        for w in ws:
            text = w.get("dp") if isinstance(w.get("dp"), str) else None
            lines.append("    { %s, %d, %d, %d, %d, %s }," % (c_str(w.get("type", "")), num(w.get("x")), num(w.get("y")),
                                                          num(w.get("w")), num(w.get("h")), c_str(text)))
            total += 1
    if total == 0:
        lines.append("    { NULL, 0, 0, 0, 0, NULL },")
    lines.append("};")
    lines.append("")
    lines.append("static const ZqUiDlgDef zq_ui_dlg_defs[] =")
    lines.append("{")
    for f, n in firsts:
        lines.append("    { %d, %d }," % (f, n))
    lines.append("};")
    lines.append("")
    lines.append("static const ZqUiDlgUse zq_ui_dlg_uses[] =")
    lines.append("{")
    for b, n, h in uses:
        lines.append("    { %s, %s, %d }," % (c_str(b), c_str(n), index[h]))
    lines.append("};")
    lines.append("")
    lines.append("static const int zq_ui_dlg_use_count = (int)(sizeof(zq_ui_dlg_uses) / sizeof(zq_ui_dlg_uses[0]));")
    open(dst, "w", newline="\n").write("\n".join(lines) + "\n")
    print("uses %d, definitions %d, widgets %d -> %s" % (len(uses), len(order), total, dst))


main()
