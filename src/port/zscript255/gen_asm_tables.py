# gen_asm_tables.py: writes zs255_zasm_defs.h and zs255_asm_tables.inc, upstream ZQuest
# Classic 2.55.17's ZASM command and register tables, copied verbatim from its source:
#   zc/ffscript.h  enum ASM_DEFINE (command numbers) and the register #defines
#   zq/ffasm.cpp   command_list[] and variable_list[] (the editor's assembler tables)
# zscript255's assembler (zs255_assemble.cpp) uses them to turn the compiler's ZASM text
# into the script records 2.55.17's ZQuest stores. Regenerate, don't hand-edit:
#   python -I gen_asm_tables.py <upstream 2.55.17 checkout>/src
import os, re, sys

src = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))

def lines(path):
    with open(os.path.join(src, path), encoding='utf-8', errors='surrogateescape', newline='') as f:
        return f.read().replace('\r\n', '\n').split('\n')

ff = lines(os.path.join('zc', 'ffscript.h'))
# enum ASM_DEFINE { ... NUMCOMMANDS };
start = next(i for i, l in enumerate(ff) if l.startswith('enum ASM_DEFINE'))
end = next(i for i in range(start, len(ff)) if ff[i].startswith('};'))
enum_block = ff[start:end + 1]
# the register defines that follow it, up to NUMVARIABLES and the internal array ids
reg_start = next(i for i in range(end, len(ff)) if re.match(r'#define D\(n\)', ff[i]))
reg_end = next(i for i in range(reg_start, len(ff)) if ff[i].startswith('#define NUMVARIABLES'))
reg_block = [l for l in ff[reg_start:reg_end + 1] if l.strip() == '' or l.lstrip().startswith(('#define', '//', '/*'))]

asm = lines(os.path.join('zq', 'ffasm.cpp'))
c0 = next(i for i, l in enumerate(asm) if l.startswith('script_command command_list['))
c1 = next(i for i in range(c0, len(asm)) if asm[i].startswith('};'))
v0 = next(i for i, l in enumerate(asm) if l.startswith('script_variable variable_list['))
v1 = next(i for i in range(v0, len(asm)) if asm[i].startswith('};'))

head = ['// Generated by gen_asm_tables.py from upstream ZQuest Classic 2.55.17 (GPL); do not edit.']
with open(os.path.join(here, 'zs255_zasm_defs.h'), 'w', encoding='utf-8', errors='surrogateescape', newline='\n') as f:
    f.write('\n'.join(head + [
        '// zc/ffscript.h: the ZASM command numbers and register numbers 2.55.17 stores.',
        '#ifndef ZS255_ZASM_DEFS_H',
        '#define ZS255_ZASM_DEFS_H',
        '// (included inside namespace zs255_asm by zs255_asm_tables.cpp)',
        ''] + enum_block + [''] + reg_block + ['', '#endif', '']))
with open(os.path.join(here, 'zs255_asm_tables.inc'), 'w', encoding='utf-8', errors='surrogateescape', newline='\n') as f:
    f.write('\n'.join(head + ['// zq/ffasm.cpp: command_list[] and variable_list[].', ''] +
                      asm[c0:c1 + 1] + [''] + asm[v0:v1 + 1] + ['']))
print('commands block %d lines, registers %d lines, tables %d + %d lines' % (
    len(enum_block), len(reg_block), c1 - c0 + 1, v1 - v0 + 1))
