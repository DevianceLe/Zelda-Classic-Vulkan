/* Fills 'f' (an empty zcport font of height 8) with the default glyphs. */
void build_default_font(FONT *f)
{
    for(size_t r = 0; r < sizeof(g_ranges) / sizeof(g_ranges[0]); ++r)
    {
        const DefaultRange &dr = g_ranges[r];
        ZCPORT_FONT_RANGE *range = zcport_font_add_range(f, dr.begin, dr.end, 1);
        if(!range)
            return;
        for(int ch = dr.begin; ch < dr.end; ++ch)
        {
            BITMAP *g = create_bitmap_ex(8, 8, 8);
            if(!g)
                return;
            const unsigned char *rows = dr.rows + (ch - dr.begin) * 8;
            for(int y = 0; y < 8; ++y)
                for(int x = 0; x < 8; ++x)
                    g->line[y][x] = (rows[y] >> (7 - x)) & 1;
            zcport_font_set_glyph(range, ch, g);
        }
    }
}

