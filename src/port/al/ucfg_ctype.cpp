int apply_rules(const CaseRule *rules, int count, int c)
{
    if(c < 0x41 || c > 0x24E9)
        return c;

    // Rules are sorted by first; few enough for a linear scan with an
    // early exit.
    for(int i = 0; i < count; ++i)
    {
        const CaseRule &r = rules[i];

        if(c < r.first)
            break;

        if(c <= r.last && ((c - r.first) % r.step) == 0)
            return c + r.delta;
    }

    return c;
}

