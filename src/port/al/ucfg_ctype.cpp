extern "C" int utolower(int c)
{
    if(c >= 'A' && c <= 'Z')
        return c + 32;

    return apply_rules(kLower, (int)(sizeof(kLower) / sizeof(kLower[0])), c);
}

extern "C" int utoupper(int c)
{
    if(c >= 'a' && c <= 'z')
        return c - 32;

    return apply_rules(kUpper, (int)(sizeof(kUpper) / sizeof(kUpper[0])), c);
}

extern "C" int uisspace(int c)
{
    // C white space plus the Unicode space separators the reference knows
    // (not U+0085, U+00A0, U+2029 or U+205F).
    return ((c >= 9 && c <= 13) || c == ' ' || c == 0x1680 || (c >= 0x2000 && c <= 0x200A) ||
            c == 0x2028 || c == 0x202F || c == 0x3000) ? 1 : 0;
}

extern "C" int uisdigit(int c)
{
    return (c >= '0' && c <= '9') ? 1 : 0;
}
